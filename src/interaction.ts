// Сброс активного взаимодействия пользователя с холстом (SPEC_NIGHT5 §7): автор скрыл страницу, на которой гость
// сейчас рисует, тянет объект или пишет текст. Контроллер и редактор текста регистрируют здесь свои обработчики,
// а совместная работа вызывает сброс, не завися от тяжёлых модулей интерфейса.

const cancellers = new Set<() => void>();

/** Зарегистрировать обработчик сброса; возвращает отписку. */
export function onCancelInteraction(fn: () => void): () => void {
  cancellers.add(fn);
  return () => { cancellers.delete(fn); };
}

/** Отменить текущий жест (рисование, перетаскивание, выделение рамкой, ластик, поворот) и закрыть редактор текста. */
export function cancelActiveInteraction(): void {
  for (const fn of [...cancellers]) {
    try { fn(); } catch { /* сброс одного не мешает остальным */ }
  }
}
