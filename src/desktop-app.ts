// Запуск установленной настольной Abax с сайта.
//
// Сайт и приложение — разные сборки с разными хранилищами, поэтому «открыть в приложении»
// умеет только одно: перейти по схеме abax://. Её регистрирует установщик (electron-builder.yml)
// и сам main-процесс (electron/main.cjs); система запускает Abax или поднимает уже открытое окно.
// Узнать заранее, установлена ли Abax, браузер не даёт, поэтому рядом с сообщением об открытии
// остаётся ссылка на скачивание — на случай, если схема в системе не зарегистрирована.

/** Схема из electron/main.cjs: команда «открыть окно». */
export const DESKTOP_PROTOCOL_URL = 'abax://open';
export const RELEASES_URL = 'https://github.com/MotoIlyuha/Abax/releases/latest';

/** Переходит по схеме abax:// — браузер передаёт ссылку системе (или спрашивает разрешение). */
export function openDesktopApp(): void {
  try {
    window.location.href = DESKTOP_PROTOCOL_URL;
  } catch {
    // Браузер может запретить переход по неизвестной схеме — тогда остаётся ссылка в тосте.
  }
}
